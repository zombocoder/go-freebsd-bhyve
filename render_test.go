// basicConfig is a VM with one of everything, used wherever a valid
// configuration is needed.
func basicConfig() Config {
	return Config{
		Name:   "gobhyve-render",
		CPU:    CPU{Count: 2, Sockets: 1, Cores: 2, Threads: 1},
		Memory: Memory{Size: 1 << 30, Wired: true},
		Firmware: &Firmware{
			ROM:  "/usr/local/share/uefi-firmware/BHYVE_UEFI.fd",
			Vars: "/var/db/vm/render/vars.fd",
		},
		Disks: []Disk{
			{Path: "/dev/zvol/zroot/vm/render", Model: DiskVirtioBlk},
			{Path: "/tmp/install.iso", Model: DiskAHCICD, ReadOnly: true},
		},
		Networks:    []Network{{Backend: "tap3", Model: NetVirtio, MAC: "58:9c:fc:00:11:22"}},
		Serials:     []Serial{{Port: COM1, Backend: "/dev/nmdm-render-A"}},
		Passthrough: []vmm.PCIDevice{{Bus: 2}},
		ACPITables:  true,
	}
}

