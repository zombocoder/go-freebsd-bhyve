// TestRenderIsDeterministic is what makes the golden file above worth
// having: variables are written sorted, not in map order.
func TestRenderIsDeterministic(t *testing.T) {
	cfg := basicConfig()
	cfg.Extra = map[string]string{"zzz": "1", "aaa": "2", "mmm": "3"}

	first, err := cfg.Render()
	if err != nil {
		t.Fatalf("Render: %v", err)
	}
	for i := 0; i < 20; i++ {
		again, err := cfg.Render()
		if err != nil {
			t.Fatalf("Render: %v", err)
		}
		if again != first {
			t.Fatal("Render() is not deterministic across calls")
		}
	}
}

// TestRenderPinsDestroyOnPowerOff guards the setting that would let
// bhyve destroy the VM out from under a holder of it.
func TestRenderPinsDestroyOnPowerOff(t *testing.T) {
	cfg := basicConfig()
	out, err := cfg.Render()
	if err != nil {
		t.Fatalf("Render: %v", err)
	}
	if !strings.Contains(out, "destroy_on_poweroff=false\n") {
		t.Error("destroy_on_poweroff is not pinned off in the rendered config")
	}
}

func TestMemoryRender(t *testing.T) {
	tests := []struct {
		size uint64
		want string
	}{
		{256 << 20, "256M"},
		{1 << 30, "1G"},
		{4 << 30, "4G"},
		{1 << 40, "1T"},
		{512 << 10, "512K"},
		{1536 << 20, "1536M"}, // not a whole number of GiB
		{100 << 20, "100M"},
		{(1 << 20) + 1, "1048577"}, // no exact suffix
	}
	for _, tc := range tests {
		if got := (Memory{Size: tc.size}).render(); got != tc.want {
			t.Errorf("Memory{%d}.render() = %q, want %q", tc.size, got, tc.want)
		}
	}
}

// TestSlotLayoutIsStable matters to the guest, which names its disks and
// interfaces by the order it finds them on the bus.
func TestSlotLayoutIsStable(t *testing.T) {
	cfg := basicConfig()

	for _, tc := range []struct {
		kind  string
		index int
		want  string
	}{
		{"disk", 0, "0/3/0"},
		{"disk", 1, "0/4/0"},
		{"network", 0, "0/5/0"},
		{"passthrough", 0, "0/6/0"},
	} {
		got, err := cfg.PCIAddress(tc.kind, tc.index)
		if err != nil {
			t.Errorf("PCIAddress(%q, %d): %v", tc.kind, tc.index, err)
			continue
		}
		if got.String() != tc.want {
			t.Errorf("PCIAddress(%q, %d) = %v, want %v",
				tc.kind, tc.index, got, tc.want)
		}
	}

	if _, err := cfg.PCIAddress("disk", 99); !errors.Is(err, ErrInvalidConfig) {
		t.Errorf("PCIAddress past the end = %v, want ErrInvalidConfig", err)
	}
	if _, err := cfg.PCIAddress("nonsense", 0); !errors.Is(err, ErrInvalidConfig) {
		t.Errorf("PCIAddress with an unknown kind = %v, want ErrInvalidConfig", err)
	}
}

func TestSlotExhaustion(t *testing.T) {
	cfg := basicConfig()
	cfg.Disks = nil
	cfg.Networks = nil
	cfg.Passthrough = nil

	// One more than the bus has room for.
	for i := 0; i <= UsablePCISlots; i++ {
		cfg.Disks = append(cfg.Disks, Disk{Path: "/tmp/disk", Model: DiskVirtioBlk})
	}

	err := cfg.Check()
	if !errors.Is(err, ErrInvalidConfig) {
		t.Fatalf("Check with %d devices = %v, want ErrInvalidConfig", len(cfg.Disks), err)
	}
	if !strings.Contains(err.Error(), "slot") {
		t.Errorf("error %q does not mention slots", err)
	}
}

// TestExtraCannotOverrideManagedKeys is the other half of the
// destroy_on_poweroff guard: the escape hatch must not reach it.
func TestExtraCannotOverrideManagedKeys(t *testing.T) {
	for _, key := range []string{
		"destroy_on_poweroff", "name", "memory.size",
		"pci.0.0.0.device", "lpc.bootrom",
	} {
		cfg := basicConfig()
		cfg.Extra = map[string]string{key: "whatever"}

		err := cfg.Check()
		if !errors.Is(err, ErrInvalidConfig) {
			t.Errorf("Extra[%q] = %v, want ErrInvalidConfig", key, err)
		}
	}

	// A key this package does not manage is fine.
	cfg := basicConfig()
	cfg.Extra = map[string]string{"bios.vendor": "ACME"}
	if err := cfg.Check(); err != nil {
		t.Errorf("Extra with an unmanaged key = %v, want nil", err)
	}
}

// TestValidateAgainstBhyve is the test the whole configuration layer
// rests on: bhyve parses what was generated, with its own parser and its
// own defaults, and reports what it understood.
//
// It needs no privilege and starts no VM, because bhyve dumps its
// configuration and exits before touching /dev/vmm.
func TestValidateAgainstBhyve(t *testing.T) {
	cfg := basicConfig()

	resolved, err := cfg.Validate(context.Background(), Tool{})
	if err != nil {
		if errors.Is(err, ErrNotFound) {
			t.Skipf("bhyve(8) is not installed: %v", err)
		}
		t.Fatalf("Validate: %v", err)
	}

	// Everything sent must have arrived. This is the only defence
	// against a misspelled variable name, which bhyve accepts in
	// silence.
	vars, err := cfg.variables()
	if err != nil {
		t.Fatalf("variables: %v", err)
	}
	for _, key := range vars.keys() {
		got, ok := resolved.Get(key)
		if !ok {
			t.Errorf("bhyve did not record %q", key)
			continue
		}
		if want := vars.pairs[key]; got != want {
			t.Errorf("bhyve resolved %q to %q, want %q", key, got, want)
		}
	}

	// And bhyve adds defaults of its own, which is the other reason
	// to ask it rather than to guess.
	if len(resolved.Vars) <= len(vars.pairs) {
		t.Errorf("bhyve reported %d variables for the %d sent, expected its own defaults too",
			len(resolved.Vars), len(vars.pairs))
	}
	t.Logf("sent %d variables, bhyve resolved %d",
		len(vars.pairs), len(resolved.Vars))
}

// TestValidateCannotCatchUnknownKey records a limitation rather than a
// feature, because the obvious assumption about it is wrong.
//
// bhyve stores every variable name it is handed, whether or not anything
// reads it, so that values can refer to each other. A misspelled name
// therefore comes back in the dump looking entirely healthy, and nothing
// bhyve offers distinguishes a variable it understands from one it is
// merely holding. Validate cannot detect this, and a test expecting it
// to would be asserting something untrue about bhyve.
//
// The protection is structural instead: every name this package manages
// is a compile-time constant, so the exposure is limited to
// Config.Extra, which is documented as sharp for exactly this reason.
func TestValidateCannotCatchUnknownKey(t *testing.T) {
	cfg := basicConfig()
	cfg.Extra = map[string]string{"memory.siz": "1G"} // a typo for memory.size

	resolved, err := cfg.Validate(context.Background(), Tool{})
	if errors.Is(err, ErrNotFound) {
		t.Skip("bhyve(8) is not installed")
	}
	if err != nil {
		t.Fatalf("Validate: %v", err)
	}

	// bhyve reports the typo back as though it meant something.
	if got, ok := resolved.Get("memory.siz"); !ok || got != "1G" {
		t.Error("bhyve dropped the unknown key; this test's premise no longer holds")
	}
	// And the setting that was meant kept its own value, which is
	// the damage a typo does.
	if got, _ := resolved.Get("memory.size"); got != "1G" {
		t.Logf("memory.size resolved to %q, so the typo did nothing, as documented", got)
	}
}

// TestValidateDoesNotCheckSemantics is the other half of the same
// caution: bhyve dumps its configuration before checking whether the
// configuration means anything.
//
// A CPU topology contradicting the vCPU count passes Validate and then
// fails at startup with "Topology (...) does not match N vCPUs".
// Config.Check is what catches it early, which is why that check exists
// in Go even though bhyve has one of its own.
func TestValidateDoesNotCheckSemantics(t *testing.T) {
	// Straight to bhyve, bypassing this package's check.
	cfg := basicConfig()
	cfg.CPU = CPU{Count: 2}
	cfg.Extra = map[string]string{"x86.strictio": "true"}

	if _, err := cfg.Validate(context.Background(), Tool{}); err != nil {
		if errors.Is(err, ErrNotFound) {
			t.Skip("bhyve(8) is not installed")
		}
		t.Fatalf("Validate: %v", err)
	}

	// The contradiction is caught locally instead.
	bad := basicConfig()
	bad.CPU = CPU{Count: 2, Sockets: 2, Cores: 7, Threads: 1}

	err := bad.Check()
	if !errors.Is(err, ErrInvalidConfig) {
		t.Fatalf("Check on a contradictory topology = %v, want ErrInvalidConfig", err)
	}
	if !strings.Contains(err.Error(), "14") {
		t.Errorf("error %q does not say how many cpus the topology describes", err)
	}
}

// TestCheckRejectsUnparsableKey covers the file format itself: a key
// containing '=' would split in the wrong place, so it never reaches
// bhyve.
func TestCheckRejectsUnparsableKey(t *testing.T) {
	for _, key := range []string{"bios.vendor=oops", "with\nnewline", ""} {
		cfg := basicConfig()
		cfg.Extra = map[string]string{key: "x"}

		if err := cfg.Check(); !errors.Is(err, ErrInvalidConfig) {
			t.Errorf("Check with key %q = %v, want ErrInvalidConfig", key, err)
		}
	}
}

func TestToolPath(t *testing.T) {
	if _, err := (Tool{Bhyve: "/nonexistent/bhyve"}).bhyvePath(); !errors.Is(err, ErrNotFound) {
		t.Errorf("bhyvePath for a missing binary = %v, want ErrNotFound", err)
	}
	if _, err := (Tool{Bhyve: "/tmp"}).bhyvePath(); !errors.Is(err, ErrNotFound) {
		t.Errorf("bhyvePath for a directory = %v, want ErrNotFound", err)
	}

	path, err := Tool{}.bhyvePath()
	if err != nil {
		if errors.Is(err, ErrNotFound) {
			t.Skip("bhyve(8) is not installed")
		}
		t.Fatalf("bhyvePath: %v", err)
	}
	if path != DefaultBhyvePath {
		t.Errorf("bhyvePath() = %q, want %q", path, DefaultBhyvePath)
	}
	if _, err := os.Stat(path); err != nil {
		t.Errorf("bhyvePath returned %q which does not stat: %v", path, err)
	}
}
