//go:build freebsd

package bhyve

import (
	"fmt"
	"sort"
	"strconv"
	"strings"
)

// variables collects configuration variables on the way to a file.
//
// Keys are written sorted rather than in the order they were set, so
// that the same configuration always renders byte for byte the same.
// That is what makes the rendered form worth comparing in a test.
type variables struct {
	pairs map[string]string
}

func newVariables() *variables {
	return &variables{pairs: make(map[string]string)}
}

// set records one variable.
func (v *variables) set(key, value string) {
	v.pairs[key] = value
}

// setBool records a boolean, which bhyve reads as "true" or "false".
func (v *variables) setBool(key string, value bool) {
	v.set(key, strconv.FormatBool(value))
}

// setInt records an integer.
func (v *variables) setInt(key string, value int) {
	v.set(key, strconv.Itoa(value))
}

// node records a variable under a device node.
func (v *variables) node(prefix, key, value string) {
	v.set(prefix+"."+key, value)
}

// nodeBool records a boolean under a device node.
func (v *variables) nodeBool(prefix, key string, value bool) {
	v.node(prefix, key, strconv.FormatBool(value))
}

// keys returns the variable names, sorted.
func (v *variables) keys() []string {
	out := make([]string, 0, len(v.pairs))
	for key := range v.pairs {
		out = append(out, key)
	}
	sort.Strings(out)
	return out
}

// render formats the variables as a bhyve configuration file.
//
// The format, from bhyve's own parser, is one key=value per line, with
// '#' comments and blank lines ignored. There is no quoting and no
// escaping: the parser splits each line at the first '=' and takes the
// rest verbatim. Values are therefore checked for newlines well before
// they reach here.
func (v *variables) render(header string) string {
	var b strings.Builder

	if header != "" {
		for _, line := range strings.Split(header, "\n") {
			b.WriteString("# ")
			b.WriteString(line)
			b.WriteByte('\n')
		}
		b.WriteByte('\n')
	}

	for _, key := range v.keys() {
		b.WriteString(key)
		b.WriteByte('=')
		b.WriteString(v.pairs[key])
		b.WriteByte('\n')
	}

	return b.String()
}

// keyPCINode is the namespace PCI device nodes live under.
const keyPCINode = "pci"

// pciPrefix is the configuration path of a PCI device node.
//
// The slot comes from this package's own allocation, never from
// caller input, so there is nothing here to sanitise.
func pciPrefix(s slot) string {
	return keyPCINode + "." + s.String()
}

// Render formats the configuration as a bhyve configuration file, the
// form bhyve reads with its -k option.
//
// The output is deterministic: the same configuration always produces
// the same bytes.
func (c *Config) Render() (string, error) {
	if err := c.Check(); err != nil {
		return "", err
	}

	v, err := c.variables()
	if err != nil {
		return "", err
	}

	return v.render("Generated by go-freebsd-bhyve. Do not edit."), nil
}

// variables builds the configuration variables for the VM, including
// whatever the caller put in Extra.
func (c *Config) variables() (*variables, error) {
	return c.build(c.Extra)
}

// managedKeys returns the variables this package sets itself, so that
// Extra can be checked for collisions with them.
func (c *Config) managedKeys() (map[string]bool, error) {
	v, err := c.build(nil)
	if err != nil {
		return nil, err
	}

	out := make(map[string]bool, len(v.pairs))
	for key := range v.pairs {
		out[key] = true
	}
	return out, nil
}

// build assembles the configuration variables.
//
// The caller's extra settings arrive as a parameter rather than being
// read from the config, so that the managed set can be computed without
// them.
func (c *Config) build(extra map[string]string) (*variables, error) {
	a, err := c.assign()
	if err != nil {
		return nil, err
	}

	v := newVariables()

	v.set(keyName, c.Name)

	v.setInt(keyCPUs, c.CPU.Count)
	if c.CPU.topology() {
		v.setInt(keySockets, c.CPU.Sockets)
		v.setInt(keyCores, c.CPU.Cores)
		v.setInt(keyThreads, c.CPU.Threads)
	}

	v.set(keyMemorySize, c.Memory.render())
	v.setBool(keyMemoryWired, c.Memory.Wired)
	v.setBool(keyMemoryGuestInCore, c.Memory.InCore)

	v.setBool(keyACPITables, c.ACPITables)
	v.setBool(keyRTCUseLocalTime, c.RTCUseLocalTime)
	v.setBool(keyX2APIC, c.X2APIC)
	v.setBool(keyVMExitOnHLT, c.VMExitOnHLT)
	v.setBool(keyVMExitOnPause, c.VMExitOnPause)

	// Always written, never left to the default.
	//
	// With this set, bhyve calls vm_destroy() itself when the guest
	// powers off, which would pull the VM out from under a Runtime
	// holding it open. Destroying a VM is this package's decision,
	// so the setting is pinned off rather than merely not set: that
	// way an Extra entry trying to turn it on is visible as a
	// conflict instead of quietly winning.
	v.setBool(keyDestroyOnPowerOff, false)

	if c.UUID != "" {
		v.set(keyUUID, c.UUID)
	}

	// The host bridge, which every guest expects to find at 0:0:0.
	v.node(pciPrefix(a.hostBridge), keyDevice, modelHostBridge)

	// The LPC bridge carries the boot ROM and the serial ports.
	v.node(pciPrefix(a.lpc), keyDevice, modelLPC)

	if c.Firmware != nil {
		v.set(keyLPCBootROM, c.Firmware.ROM)
		if c.Firmware.Vars != "" {
			v.set(keyLPCBootVars, c.Firmware.Vars)
		}
	}

	for _, s := range c.Serials {
		// Serial ports live under the top-level lpc node rather
		// than under the LPC device's PCI node.
		v.set("lpc."+s.Port.String()+"."+keyPath, s.Backend)
	}

	for i := range c.Disks {
		c.renderDisk(v, pciPrefix(a.disks[i]), &c.Disks[i])
	}
	for i := range c.Networks {
		c.renderNetwork(v, pciPrefix(a.networks[i]), &c.Networks[i])
	}
	for i, dev := range c.Passthrough {
		prefix := pciPrefix(a.passthrough[i])
		v.node(prefix, keyDevice, modelPassthru)
		// bhyve addresses the host device by its own bus address.
		v.node(prefix, "bus", strconv.Itoa(int(dev.Bus)))
		v.node(prefix, "slot", strconv.Itoa(int(dev.Slot)))
		v.node(prefix, "func", strconv.Itoa(int(dev.Function)))
	}
	if c.Framebuffer != nil {
		c.renderFramebuffer(v, pciPrefix(*a.framebuffer), c.Framebuffer)
	}

	// Last, although Check refuses any collision with the variables
	// above, so in practice these only ever add.
	for key, value := range extra {
		v.set(key, value)
	}

	return v, nil
}

// renderDisk writes one block device node.
func (c *Config) renderDisk(v *variables, prefix string, d *Disk) {
	model, _ := d.Model.model()

	v.node(prefix, keyDevice, model)
	v.node(prefix, keyPath, d.Path)

	if d.ReadOnly {
		v.nodeBool(prefix, keyReadOnly, true)
	}
	if d.NoCache {
		v.nodeBool(prefix, keyNoCache, true)
	}
	if d.Direct {
		v.nodeBool(prefix, keyDirect, true)
	}
	if d.SectorSize != "" {
		v.node(prefix, keySectSize, d.SectorSize)
	}
}

// renderNetwork writes one network device node.
func (c *Config) renderNetwork(v *variables, prefix string, n *Network) {
	model, _ := n.Model.model()

	v.node(prefix, keyDevice, model)

	// The host side is named by "backend" for virtio-net and by
	// "path" for the emulated e1000; bhyve accepts "backend" for
	// both, which keeps this uniform.
	v.node(prefix, keyBackend, n.Backend)

	if n.MAC != "" {
		v.node(prefix, "mac", n.MAC)
	}
}

// renderFramebuffer writes the framebuffer device node.
func (c *Config) renderFramebuffer(v *variables, prefix string, f *Framebuffer) {
	v.node(prefix, keyDevice, modelFramebuffer)

	// Default to localhost rather than to every interface: the VNC
	// server offers no transport security, so a wider bind would be
	// a surprising thing for a library to choose.
	host := f.Host
	if host == "" {
		host = "127.0.0.1"
	}
	v.node(prefix, keyFBHost, host)

	if f.Port != 0 {
		v.node(prefix, keyFBPort, strconv.Itoa(f.Port))
	}
	if f.Width != 0 {
		v.node(prefix, keyFBWidth, strconv.Itoa(f.Width))
	}
	if f.Height != 0 {
		v.node(prefix, keyFBHeight, strconv.Itoa(f.Height))
	}
	if f.Wait {
		v.nodeBool(prefix, keyFBWait, true)
	}
}

// String renders the configuration for diagnostics, falling back to the
// error when it cannot be rendered.
func (c *Config) String() string {
	out, err := c.Render()
	if err != nil {
		return fmt.Sprintf("<invalid config: %v>", err)
	}
	return out
}
